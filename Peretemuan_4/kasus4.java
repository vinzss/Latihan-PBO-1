package Peretemuan_4;

public class kasus4 {
    // Variabel dengan akses modifier private
    private String title;
    private String author;
    private int price;
    private String isbn;
    private int year;

    // Getter dan Setter untuk title
    public void setTitle(String title) {
        this.title = title;
    }

    public String getTitle() {
        return this.title;
    }

    // Getter dan Setter untuk author
    public void setAuthor(String author) {
        this.author = author;
    }

    public String getAuthor() {
        return this.author;
    }

    // Getter dan Setter untuk price
    public void setPrice(int price) {
        this.price = price;
    }

    public int getPrice() {
        return this.price;
    }

    // Getter dan Setter untuk isbn
    public void setIsbn(String isbn) {
        this.isbn = isbn;
    }

    public String getIsbn() {
        return this.isbn;
    }

    // Getter dan Setter untuk year
    public void setYear(int year) {
        this.year = year;
    }

    public int getYear() {
        return this.year;
    }
}
